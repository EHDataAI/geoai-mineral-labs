def repo_root() -> Path:
    """Resolve repository root from builder location."""
    return Path(__file__).resolve().parents[2]


def current_branch(root: Path) -> str:
    """Read current Git branch."""
    result = subprocess.run(
        ["git", "branch", "--show-current"],
        cwd=root,
        check=True,
        capture_output=True,
        text=True,
    )

    return result.stdout.strip()


def write_file(
    root: Path,
    relative: str,
    content: str,
) -> None:
    """Write one canonical UTF-8 file."""
    path = root / relative

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    path.write_text(
        content.rstrip() + "\n",
        encoding="utf-8",
    )

    print(f"WRITTEN = {relative}")


