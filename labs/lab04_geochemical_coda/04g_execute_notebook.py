"""Execute and quality-check the LAB04 geochemical CoDA notebook."""

from __future__ import annotations

import json
from pathlib import Path

import nbformat
from nbclient import NotebookClient
from nbclient.exceptions import CellExecutionError


LAB_DIR = Path(__file__).resolve().parent
INPUT_NOTEBOOK = LAB_DIR / "04_geochemical_coda.ipynb"
OUTPUT_NOTEBOOK = LAB_DIR / "04_geochemical_coda_executed.ipynb"


def count_outputs(
    notebook: nbformat.NotebookNode,
) -> tuple[int, int, int]:
    """Return counts for total outputs, image outputs, and error outputs."""
    total_outputs = 0
    image_outputs = 0
    error_outputs = 0

    for cell in notebook.cells:
        if cell.cell_type != "code":
            continue

        for output in cell.get("outputs", []):
            total_outputs += 1

            if output.get("output_type") == "error":
                error_outputs += 1

            data = output.get("data", {})

            if isinstance(data, dict) and "image/png" in data:
                image_outputs += 1

    return total_outputs, image_outputs, error_outputs


def count_unexecuted_code_cells(
    notebook: nbformat.NotebookNode,
) -> int:
    """Count non-empty code cells without an execution count."""
    count = 0

    for cell in notebook.cells:
        if cell.cell_type != "code":
            continue

        if not cell.source.strip():
            continue

        if cell.get("execution_count") is None:
            count += 1

    return count


def validate_unicode(
    path: Path,
) -> tuple[bool, int, int]:
    """Check BOM, replacement characters, and literal question marks."""
    raw = path.read_bytes()
    text = raw.decode("utf-8")

    has_bom = raw.startswith(b"\xef\xbb\xbf")
    replacement_characters = text.count("\ufffd")

    notebook = json.loads(text)

    question_marks = 0

    for cell in notebook.get("cells", []):
        source = cell.get("source", [])

        if isinstance(source, list):
            source = "".join(source)

        question_marks += source.count("?")

    return (
        has_bom,
        replacement_characters,
        question_marks,
    )


def main() -> None:
    """Execute the notebook and validate its outputs."""
    if not INPUT_NOTEBOOK.exists():
        raise FileNotFoundError(
            f"Input notebook not found: {INPUT_NOTEBOOK}"
        )

    with INPUT_NOTEBOOK.open(
        "r",
        encoding="utf-8",
    ) as handle:
        notebook = nbformat.read(
            handle,
            as_version=4,
        )

    client = NotebookClient(
        notebook,
        timeout=300,
        kernel_name="python3",
        resources={
            "metadata": {
                "path": str(LAB_DIR),
            }
        },
        allow_errors=False,
    )

    try:
        executed = client.execute()

    except CellExecutionError as exc:
        print("LAB04_NOTEBOOK_EXECUTION = FAIL")

        raise RuntimeError(
            "Notebook execution failed. "
            "Review the failing cell above."
        ) from exc

    with OUTPUT_NOTEBOOK.open(
        "w",
        encoding="utf-8",
        newline="\n",
    ) as handle:
        nbformat.write(
            executed,
            handle,
        )

    (
        total_outputs,
        image_outputs,
        error_outputs,
    ) = count_outputs(executed)

    unexecuted_code_cells = (
        count_unexecuted_code_cells(executed)
    )

    (
        has_bom,
        replacement_characters,
        question_marks,
    ) = validate_unicode(OUTPUT_NOTEBOOK)

    if error_outputs != 0:
        raise RuntimeError(
            "Executed notebook contains "
            f"{error_outputs} error outputs."
        )

    if unexecuted_code_cells != 0:
        raise RuntimeError(
            "Executed notebook contains non-empty "
            "code cells without execution_count: "
            f"{unexecuted_code_cells}"
        )

    if image_outputs == 0:
        raise RuntimeError(
            "No PNG outputs were generated by the notebook."
        )

    if has_bom:
        raise RuntimeError(
            "Executed notebook contains a UTF-8 BOM."
        )

    if replacement_characters != 0:
        raise RuntimeError(
            "Executed notebook contains Unicode "
            "replacement characters."
        )

    if question_marks != 0:
        raise RuntimeError(
            "Executed notebook contains literal "
            "question marks in cells."
        )

    print("LAB04_NOTEBOOK_EXECUTION = PASS")
    print("OUTPUT =", OUTPUT_NOTEBOOK)
    print("CELLS =", len(executed.cells))
    print("TOTAL_OUTPUTS =", total_outputs)
    print("PNG_OUTPUTS =", image_outputs)
    print("ERROR_OUTPUTS =", error_outputs)

    print(
        "UNEXECUTED_CODE_CELLS =",
        unexecuted_code_cells,
    )

    print(
        "UTF8_BOM =",
        has_bom,
    )

    print(
        "UNICODE_REPLACEMENT_CHARACTERS =",
        replacement_characters,
    )

    print(
        "LITERAL_QUESTION_MARKS_IN_CELLS =",
        question_marks,
    )


if __name__ == "__main__":
    main()
