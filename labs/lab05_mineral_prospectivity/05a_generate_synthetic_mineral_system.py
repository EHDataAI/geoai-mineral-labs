"""Generate the synthetic mineral system for LAB05.

The synthetic mineral system represents geology, structure,
geophysics, alteration, spatial validation groups, and a sealed
synthetic mineralization oracle.

Oracle variables generated by this module must never be used as
model predictors.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from prospectivity_config import SEED, STUDY_AREA


LAB_DIR = Path(__file__).resolve().parent
DATA_DIR = LAB_DIR / "data"
RESULTS_DIR = LAB_DIR / "results"

OUTPUT_PATH = DATA_DIR / "synthetic_mineral_system.csv"
SUMMARY_PATH = RESULTS_DIR / "synthetic_system_summary.json"


def build_grid() -> pd.DataFrame:
    """Create a regular grid using cell-centre coordinates."""
    cell_size = int(STUDY_AREA["grid_cell_size_m"])

    eastings = np.arange(
        STUDY_AREA["easting_min"],
        STUDY_AREA["easting_max"],
        cell_size,
        dtype=float,
    )

    northings = np.arange(
        STUDY_AREA["northing_min"],
        STUDY_AREA["northing_max"],
        cell_size,
        dtype=float,
    )

    x, y = np.meshgrid(eastings, northings)

    grid = pd.DataFrame(
        {
            "Easting": x.ravel() + cell_size / 2.0,
            "Northing": y.ravel() + cell_size / 2.0,
        }
    )

    grid["cell_id"] = np.arange(len(grid), dtype=int)

    return grid


def gaussian_field(
    x: np.ndarray,
    y: np.ndarray,
    center_x: float,
    center_y: float,
    sigma_x: float,
    sigma_y: float,
) -> np.ndarray:
    """Return an anisotropic Gaussian spatial field."""
    dx = (x - center_x) / sigma_x
    dy = (y - center_y) / sigma_y

    return np.exp(-0.5 * (dx**2 + dy**2))


def distance_to_line(
    x: np.ndarray,
    y: np.ndarray,
    slope: float,
    intercept: float,
) -> np.ndarray:
    """Return point-to-line distance for y = slope*x + intercept."""
    numerator = np.abs(slope * x - y + intercept)
    denominator = np.sqrt(slope**2 + 1.0)

    return numerator / denominator


def add_geological_evidence(
    grid: pd.DataFrame,
    rng: np.random.Generator,
) -> pd.DataFrame:
    """Generate geological, structural, geophysical and alteration fields."""
    result = grid.copy()

    x = result["Easting"].to_numpy()
    y = result["Northing"].to_numpy()

    intrusive_a = gaussian_field(
        x,
        y,
        center_x=382000.0,
        center_y=7145000.0,
        sigma_x=12000.0,
        sigma_y=9000.0,
    )

    intrusive_b = gaussian_field(
        x,
        y,
        center_x=404000.0,
        center_y=7160000.0,
        sigma_x=9000.0,
        sigma_y=12000.0,
    )

    intrusive_affinity = np.maximum(
        intrusive_a,
        intrusive_b,
    )

    result["intrusive_affinity"] = intrusive_affinity

    result["distance_to_intrusive_m"] = (
        30000.0 * (1.0 - intrusive_affinity)
    )

    result["lithology"] = np.select(
        [
            intrusive_affinity > 0.72,
            intrusive_affinity > 0.42,
            y > 7158000.0,
        ],
        [
            "intrusive",
            "volcanic",
            "sedimentary",
        ],
        default="volcaniclastic",
    )

    fault_a = distance_to_line(
        x,
        y,
        slope=0.60,
        intercept=6915000.0,
    )

    fault_b = distance_to_line(
        x,
        y,
        slope=-0.45,
        intercept=7330000.0,
    )

    fault_c = distance_to_line(
        x,
        y,
        slope=0.10,
        intercept=7100000.0,
    )

    result["distance_to_fault_m"] = np.minimum.reduce(
        [fault_a, fault_b, fault_c]
    )

    intersection_x = 392000.0
    intersection_y = 7152000.0

    result["distance_to_fault_intersection_m"] = np.sqrt(
        (x - intersection_x) ** 2
        + (y - intersection_y) ** 2
    )

    result["distance_to_contact_m"] = (
        np.abs(intrusive_affinity - 0.48) * 24000.0
    )

    structural_signal = np.exp(
        -result["distance_to_fault_m"].to_numpy()
        / 7000.0
    )

    intersection_signal = np.exp(
        -result[
            "distance_to_fault_intersection_m"
        ].to_numpy()
        / 12000.0
    )

    result["magnetic_anomaly"] = (
        65.0 * intrusive_affinity
        + 20.0 * structural_signal
        + rng.normal(0.0, 8.0, len(result))
    )

    result["gravity_anomaly"] = (
        35.0 * intrusive_affinity
        - 12.0 * structural_signal
        + rng.normal(0.0, 6.0, len(result))
    )

    alteration_signal = (
        0.50 * intrusive_affinity
        + 0.30 * structural_signal
        + 0.20 * intersection_signal
    )

    result["alteration_index"] = np.clip(
        alteration_signal
        + rng.normal(0.0, 0.08, len(result)),
        0.0,
        1.0,
    )

    return result


def add_synthetic_oracle(
    data: pd.DataFrame,
    rng: np.random.Generator,
) -> pd.DataFrame:
    """Generate sealed latent favourability and true deposits."""
    result = data.copy()

    source = result["intrusive_affinity"].to_numpy()

    pathway = np.exp(
        -result["distance_to_fault_m"].to_numpy()
        / 6000.0
    )

    intersection = np.exp(
        -result[
            "distance_to_fault_intersection_m"
        ].to_numpy()
        / 10000.0
    )

    contact = np.exp(
        -result["distance_to_contact_m"].to_numpy()
        / 5000.0
    )

    alteration = result["alteration_index"].to_numpy()

    lithology_bonus = np.select(
        [
            result["lithology"].to_numpy()
            == "intrusive",
            result["lithology"].to_numpy()
            == "volcanic",
        ],
        [
            0.20,
            0.10,
        ],
        default=0.0,
    )

    noise = rng.normal(
        0.0,
        0.22,
        len(result),
    )

    latent = (
        0.31 * source
        + 0.22 * pathway
        + 0.16 * intersection
        + 0.14 * contact
        + 0.17 * alteration
        + lithology_bonus
        + noise
    )

    latent = (
        latent - latent.min()
    ) / (
        latent.max() - latent.min()
    )

    result["latent_favourability"] = latent

    logit = -8.5 + 9.0 * latent

    probability = 1.0 / (
        1.0 + np.exp(-logit)
    )

    result["true_deposit_probability"] = probability

    result["true_deposit"] = rng.binomial(
        n=1,
        p=probability,
        size=len(result),
    ).astype(int)

    return result


def reveal_known_occurrences(
    data: pd.DataFrame,
    rng: np.random.Generator,
) -> pd.DataFrame:
    """Reveal half of true deposits and keep the remainder hidden."""
    result = data.copy()

    result["known_positive"] = 0
    result["deposit_id"] = ""

    deposit_indices = result.index[
        result["true_deposit"] == 1
    ].to_numpy()

    n_true = len(deposit_indices)

    if n_true < 2:
        raise RuntimeError(
            "Synthetic system produced too few true deposits."
        )

    n_known = max(
        1,
        int(np.floor(n_true * 0.50)),
    )

    known_indices = rng.choice(
        deposit_indices,
        size=n_known,
        replace=False,
    )

    result.loc[
        known_indices,
        "known_positive",
    ] = 1

    result.loc[
        known_indices,
        "deposit_id",
    ] = [
        f"DEP_{index:03d}"
        for index in range(
            1,
            n_known + 1,
        )
    ]

    return result


def assign_spatial_blocks(
    data: pd.DataFrame,
) -> pd.DataFrame:
    """Assign deterministic 10 km spatial validation blocks."""
    result = data.copy()

    x_origin = float(
        STUDY_AREA["easting_min"]
    )

    y_origin = float(
        STUDY_AREA["northing_min"]
    )

    block_size = 10000.0

    block_x = (
        (
            result["Easting"]
            - x_origin
        )
        // block_size
    ).astype(int)

    block_y = (
        (
            result["Northing"]
            - y_origin
        )
        // block_size
    ).astype(int)

    result["spatial_block_id"] = (
        "B"
        + block_x.astype(str).str.zfill(2)
        + "_"
        + block_y.astype(str).str.zfill(2)
    )

    return result


def validate_system(
    data: pd.DataFrame,
) -> dict[str, int | float]:
    """Validate Gate 1 scientific invariants."""
    expected_rows = int(
        STUDY_AREA["expected_grid_cells"]
    )

    if len(data) != expected_rows:
        raise ValueError(
            f"Expected {expected_rows} rows, "
            f"received {len(data)}."
        )

    if data["cell_id"].duplicated().any():
        raise ValueError(
            "cell_id must be unique."
        )

    if data[
        ["Easting", "Northing"]
    ].duplicated().any():
        raise ValueError(
            "Grid coordinates must be unique."
        )

    if not data[
        "latent_favourability"
    ].between(0.0, 1.0).all():
        raise ValueError(
            "latent_favourability outside [0, 1]."
        )

    if not data[
        "true_deposit_probability"
    ].between(0.0, 1.0).all():
        raise ValueError(
            "true_deposit_probability outside [0, 1]."
        )

    true_count = int(
        data["true_deposit"].sum()
    )

    known_count = int(
        data["known_positive"].sum()
    )

    hidden_count = (
        true_count - known_count
    )

    if true_count < 5:
        raise ValueError(
            "Synthetic system has fewer than 5 true deposits."
        )

    if true_count > 500:
        raise ValueError(
            "Synthetic system has more than 500 true deposits."
        )

    if known_count <= 0:
        raise ValueError(
            "At least one known occurrence is required."
        )

    if hidden_count <= 0:
        raise ValueError(
            "At least one hidden deposit is required."
        )

    invalid_known = data.loc[
        data["known_positive"] == 1,
        "true_deposit",
    ].ne(1)

    if invalid_known.any():
        raise ValueError(
            "Known positives must be true deposits."
        )

    summary = {
        "rows": int(len(data)),
        "true_deposits": true_count,
        "known_positives": known_count,
        "hidden_deposits": hidden_count,
        "deposit_prevalence": float(
            true_count / len(data)
        ),
        "spatial_blocks": int(
            data[
                "spatial_block_id"
            ].nunique()
        ),
        "latent_min": float(
            data[
                "latent_favourability"
            ].min()
        ),
        "latent_max": float(
            data[
                "latent_favourability"
            ].max()
        ),
    }

    return summary


def main() -> None:
    """Generate and persist Gate 1 outputs."""
    DATA_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    RESULTS_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    rng = np.random.default_rng(SEED)

    data = build_grid()

    data = add_geological_evidence(
        data,
        rng,
    )

    data = add_synthetic_oracle(
        data,
        rng,
    )

    data = reveal_known_occurrences(
        data,
        rng,
    )

    data = assign_spatial_blocks(
        data
    )

    summary = validate_system(data)

    data.to_csv(
        OUTPUT_PATH,
        index=False,
        encoding="utf-8",
    )

    SUMMARY_PATH.write_text(
        json.dumps(
            summary,
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )

    print("LAB05_GATE01 = PASS")

    for key, value in summary.items():
        print(
            f"{key.upper()} = {value}"
        )

    print(f"DATA = {OUTPUT_PATH}")
    print(f"SUMMARY = {SUMMARY_PATH}")


if __name__ == "__main__":
    main()
